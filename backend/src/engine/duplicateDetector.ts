import { RawReview } from '../types';

/**
 * Normalizes text for comparison: lowercase, remove punctuation and extra spaces.
 */
export function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Creates character or word n-grams from a string.
 */
export function getWordNGrams(text: string, n = 3): Set<string> {
  const words = normalizeText(text).split(' ');
  const ngrams = new Set<string>();
  if (words.length < n) {
    if (words.length > 0) ngrams.add(words.join(' '));
    return ngrams;
  }
  for (let i = 0; i <= words.length - n; i++) {
    ngrams.add(words.slice(i, i + n).join(' '));
  }
  return ngrams;
}

/**
 * Calculates Jaccard similarity between two sets of n-grams.
 */
export function jaccardSimilarity(setA: Set<string>, setB: Set<string>): number {
  if (setA.size === 0 && setB.size === 0) return 1;
  if (setA.size === 0 || setB.size === 0) return 0;
  let intersection = 0;
  for (const item of setA) {
    if (setB.has(item)) intersection++;
  }
  const union = setA.size + setB.size - intersection;
  return union === 0 ? 0 : intersection / union;
}

/**
 * Known template phrases commonly generated by bot syndicates or review-farming scripts.
 */
const SUSPICIOUS_TEMPLATES = [
  'i received this product for free or at a discount in exchange for my honest review',
  'five stars best product ever',
  'great item arrived on time will buy again',
  'highly recommend this to everyone wonderful experience',
  'amazing quality very fast shipping thank you seller',
  'worth every single penny absolutely love it',
  'must buy product good quality nice sound nice battery',
  'super fast delivery genuine product awesome',
  'dont think just buy it',
  'works as expected no issues so far five stars'
];

export interface DuplicateDetectionResult {
  flaggedReviewIds: Set<string>;
  duplicateClusters: Array<{ originalId: string; duplicates: string[]; similarity: number }>;
  templateMatchedIds: Set<string>;
  duplicateRatio: number;
}

/**
 * Scans a list of reviews for duplicate, near-duplicate, and syndicated template reviews.
 */
export function detectDuplicates(reviews: RawReview[]): DuplicateDetectionResult {
  const flaggedReviewIds = new Set<string>();
  const templateMatchedIds = new Set<string>();
  const duplicateClusters: Array<{ originalId: string; duplicates: string[]; similarity: number }> = [];

  const ngramsList = reviews.map(r => ({
    id: r.id,
    text: r.text,
    normalized: normalizeText(r.text),
    ngrams: getWordNGrams(r.text, 3)
  }));

  // Check against known bot templates
  for (const item of ngramsList) {
    for (const tpl of SUSPICIOUS_TEMPLATES) {
      if (item.normalized.includes(tpl)) {
        templateMatchedIds.add(item.id);
        flaggedReviewIds.add(item.id);
        break;
      }
    }
  }

  // Cross-compare reviews to detect duplicates or near-duplicates
  for (let i = 0; i < ngramsList.length; i++) {
    const cur = ngramsList[i];
    if (cur.normalized.length < 15) continue; // Skip very short reviews for pairwise check

    const matchedDupes: string[] = [];
    for (let j = i + 1; j < ngramsList.length; j++) {
      const other = ngramsList[j];
      if (other.normalized.length < 15) continue;

      // Exact match check
      if (cur.normalized === other.normalized) {
        matchedDupes.push(other.id);
        flaggedReviewIds.add(cur.id);
        flaggedReviewIds.add(other.id);
        continue;
      }

      // N-gram Jaccard similarity (threshold 0.65 indicates severe paraphrasing or copied template)
      const sim = jaccardSimilarity(cur.ngrams, other.ngrams);
      if (sim >= 0.65) {
        matchedDupes.push(other.id);
        flaggedReviewIds.add(cur.id);
        flaggedReviewIds.add(other.id);
      }
    }

    if (matchedDupes.length > 0) {
      duplicateClusters.push({
        originalId: cur.id,
        duplicates: matchedDupes,
        similarity: 0.85
      });
    }
  }

  const duplicateRatio = reviews.length > 0 ? flaggedReviewIds.size / reviews.length : 0;

  return {
    flaggedReviewIds,
    duplicateClusters,
    templateMatchedIds,
    duplicateRatio
  };
}
